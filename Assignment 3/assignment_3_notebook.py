def compute_score(acc, min_thres=65, max_thres=80):
  # Your Score thresholds
  if acc <= min_thres:
    base_score = 0.0
  elif acc >= max_thres:
    base_score = 100.0
  else:
    base_score = float(acc - min_thres) / (max_thres - min_thres) * 100
  return base_score

