def test(net, testloader, device):
    correct = 0
    total = 0
    ###
    net.eval()

    with torch.no_grad():
      for data,target  in testloader:
        data = data.to(device)
        target = target.to(device)
        output = net(data)
        _,predicted = torch.max(output,dim=1)

        total += target.size(0)
        correct +=(predicted==target).sum().item()

    return 100.*correct/total, correct, total

